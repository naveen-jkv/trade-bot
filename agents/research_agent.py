"""
AI Research Agent.
Formulates structured trading hypotheses using Large Language Models
or deterministic quantitative reasoning, strictly grounded in verifiable market data.
Retrieves relevant historical lessons from persistent memory before generating ideas.
Never invents prices or claims certainty.
"""

from dataclasses import dataclass, asdict
from datetime import datetime, timezone
import json
import logging
import os
from typing import Dict, List, Optional, Any
import requests

from agents.market_agent import MarketAnalysisReport
from database.memory import TradingMemoryDB
from config import LLMSettings, DEFAULT_CONFIG, SUPPORTED_PAIRS

logger = logging.getLogger("AIResearchAgent")


@dataclass
class TradingHypothesis:
    """Structured hypothesis generated by the AI Research Agent."""
    id: Optional[int]
    symbol: str
    timeframe: str
    timestamp: str
    direction: str                     # 'BUY', 'SELL', 'HOLD'
    confidence: float                  # 0.0 to 1.0
    hypothesis_text: str               # Detailed rationale and macro/micro reasoning
    invalidation_criteria: str         # Concrete condition invalidating the thesis
    proposed_entry: float
    proposed_stop_loss: float
    proposed_take_profit: float
    market_regime: str
    retrieved_lessons_applied: List[str]
    model_provider_used: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class AIResearchAgent:
    """
    Research brain of the trading system.
    Queries persistent memory for historical context in the same regime,
    synthesizes market analysis, and prompts an LLM (Gemini, OpenAI, Ollama)
    or high-fidelity quantitative reasoning engine to generate an actionable hypothesis.
    """

    def __init__(
        self,
        llm_settings: Optional[LLMSettings] = None,
        db: Optional[TradingMemoryDB] = None,
    ):
        self.settings = llm_settings or DEFAULT_CONFIG.llm
        self.db = db or TradingMemoryDB(DEFAULT_CONFIG.db_path)

    def generate_hypothesis(
        self,
        report: MarketAnalysisReport,
    ) -> TradingHypothesis:
        """
        Main entry point:
        1. Retrieves historical lessons from memory for (symbol, regime).
        2. Constructs a strictly grounded prompt with exact market prices.
        3. Calls configured LLM or heuristic reasoner.
        4. Parses and validates output against mathematical constraints.
        5. Persists hypothesis to SQLite database.
        """
        # 1. Retrieve Historical Memory Context
        past_lessons = self.db.retrieve_relevant_lessons(
            symbol=report.symbol,
            regime=report.volatility_regime,
            limit=4,
        )
        applied_lessons = [
            f"Rule: {l['rule_learned']} (Context: {l['mistake_analysis']})"
            for l in past_lessons
        ]

        # 2. Generate Reasoning via Provider
        provider = self.settings.provider.lower()
        hypothesis_dict = None

        if provider == "gemini" or (provider == "auto" and self.settings.gemini_api_key):
            hypothesis_dict = self._query_gemini(report, applied_lessons)

        if not hypothesis_dict and (provider == "openai" or (provider == "auto" and self.settings.openai_api_key)):
            hypothesis_dict = self._query_openai(report, applied_lessons)

        if not hypothesis_dict and provider == "ollama":
            hypothesis_dict = self._query_ollama(report, applied_lessons)

        # Fallback to deterministic quantitative reasoning engine
        if not hypothesis_dict:
            hypothesis_dict = self._deterministic_quant_reasoning(report, applied_lessons)
            provider_used = "Deterministic Quantitative Engine (Zero-Hallucination Fallback)"
        else:
            provider_used = f"LLM ({hypothesis_dict.get('model_tag', 'Configured Model')})"

        ts = datetime.now(timezone.utc).isoformat()

        # 3. Store Hypothesis in Database
        hyp_id = None
        try:
            hyp_id = self.db.store_hypothesis(
                symbol=report.symbol,
                timeframe=report.timeframe,
                direction=hypothesis_dict["direction"],
                confidence=hypothesis_dict["confidence"],
                hypothesis_text=hypothesis_dict["hypothesis_text"],
                invalidation_criteria=hypothesis_dict["invalidation_criteria"],
                indicators_snapshot=report.technical_state.to_dict(),
                market_regime=report.volatility_regime,
                timestamp=ts,
            )
            self.db.store_log(
                agent_name="AIResearchAgent",
                level="DECISION",
                message=f"Formulated hypothesis for {report.symbol}: {hypothesis_dict['direction']} (Conf: {hypothesis_dict['confidence']:.2f}) - {hypothesis_dict['hypothesis_text'][:90]}...",
                metadata={"hypothesis_id": hyp_id, "provider": provider_used},
            )
        except Exception as e:
            logger.warning(f"Failed to persist research hypothesis to DB: {e}")

        return TradingHypothesis(
            id=hyp_id,
            symbol=report.symbol,
            timeframe=report.timeframe,
            timestamp=ts,
            direction=hypothesis_dict["direction"],
            confidence=hypothesis_dict["confidence"],
            hypothesis_text=hypothesis_dict["hypothesis_text"],
            invalidation_criteria=hypothesis_dict["invalidation_criteria"],
            proposed_entry=hypothesis_dict["proposed_entry"],
            proposed_stop_loss=hypothesis_dict["proposed_stop_loss"],
            proposed_take_profit=hypothesis_dict["proposed_take_profit"],
            market_regime=report.volatility_regime,
            retrieved_lessons_applied=applied_lessons,
            model_provider_used=provider_used,
        )

    def _build_system_prompt(self) -> str:
        return (
            "You are an expert quantitative research analyst and Forex trader. "
            "Your task is to analyze market data, apply historical lessons, and generate a disciplined trading hypothesis. "
            "CRITICAL CONSTRAINTS:\n"
            "1. NEVER invent or hallucinate market prices. Ground every calculation in the provided numbers.\n"
            "2. Never claim predictions are certain. Markets are inherently probabilistic.\n"
            "3. Enforce a minimum 1:1.5 Risk-to-Reward ratio.\n"
            "4. Output strictly valid JSON matching the required schema with no extra conversational text.\n"
        )

    def _build_user_prompt(self, r: MarketAnalysisReport, lessons: List[str]) -> str:
        s = r.technical_state
        lessons_text = "\n".join([f"- {l}" for l in lessons]) if lessons else "No prior lessons in database for this regime."

        return f"""
Current Market Context for {r.symbol} ({r.timeframe}):
- Current Price: {r.current_price:.5f}
- Trend Direction: {s.trend_direction}
- Volatility Regime: {r.volatility_regime} (Annualized: {s.volatility_annualized * 100:.1f}%)
- RSI (14): {s.rsi_14:.1f}
- MACD Line: {s.macd:.5f}, Signal: {s.macd_signal:.5f}, Histogram: {s.macd_hist:.5f}
- EMAs: 9={s.ema_9:.5f}, 21={s.ema_21:.5f}, 50={s.ema_50:.5f}, 200={s.ema_200 or 'N/A'}
- Bollinger Bands: Upper={s.bb_upper:.5f}, Mid={s.bb_middle:.5f}, Lower={s.bb_lower:.5f}, %B={s.bb_pct_b:.2f}
- ATR (14): {s.atr_pips:.1f} pips ({s.atr_14:.5f})
- Local Support: {r.support_level:.5f}, Local Resistance: {r.resistance_level:.5f}
- Candlestick Patterns Detected: {', '.join(r.candle_patterns) if r.candle_patterns else 'None'}
- Statistical Skew: {r.stats_summary.get('skewness', 0):.2f}, Kurtosis: {r.stats_summary.get('kurtosis', 0):.2f}

Persistent Memory Lessons Retrieved:
{lessons_text}

Generate a JSON response with exactly these keys:
{{
  "direction": "BUY" | "SELL" | "HOLD",
  "confidence": float (0.0 to 1.0),
  "hypothesis_text": "2-3 sentences explaining technical rationale, momentum, and risk balance",
  "invalidation_criteria": "Specific price level and condition that completely invalidates this thesis",
  "proposed_entry": float,
  "proposed_stop_loss": float,
  "proposed_take_profit": float
}}
"""

    def _query_gemini(self, report: MarketAnalysisReport, lessons: List[str]) -> Optional[Dict[str, Any]]:
        """Invokes Google Gemini API if API key is provided."""
        api_key = self.settings.gemini_api_key
        if not api_key:
            return None

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.settings.gemini_model}:generateContent?key={api_key}"
        prompt = self._build_system_prompt() + "\n" + self._build_user_prompt(report, lessons)

        payload = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": self.settings.temperature, "responseMimeType": "application/json"}
        }

        try:
            resp = requests.post(url, json=payload, timeout=12)
            if resp.status_code == 200:
                data = resp.json()
                text = data["candidates"][0]["content"]["parts"][0]["text"]
                res = json.loads(text)
                res["model_tag"] = f"Gemini ({self.settings.gemini_model})"
                return self._sanitize_hypothesis(res, report)
        except Exception as e:
            logger.debug(f"Gemini API query failed: {e}")
        return None

    def _query_openai(self, report: MarketAnalysisReport, lessons: List[str]) -> Optional[Dict[str, Any]]:
        """Invokes OpenAI API if API key is provided."""
        api_key = self.settings.openai_api_key
        if not api_key:
            return None

        url = "https://api.openai.com/v1/chat/completions"
        headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
        payload = {
            "model": self.settings.openai_model,
            "messages": [
                {"role": "system", "content": self._build_system_prompt()},
                {"role": "user", "content": self._build_user_prompt(report, lessons)},
            ],
            "response_format": {"type": "json_object"},
            "temperature": self.settings.temperature,
        }

        try:
            resp = requests.post(url, headers=headers, json=payload, timeout=12)
            if resp.status_code == 200:
                data = resp.json()
                content = data["choices"][0]["message"]["content"]
                res = json.loads(content)
                res["model_tag"] = f"OpenAI ({self.settings.openai_model})"
                return self._sanitize_hypothesis(res, report)
        except Exception as e:
            logger.debug(f"OpenAI API query failed: {e}")
        return None

    def _query_ollama(self, report: MarketAnalysisReport, lessons: List[str]) -> Optional[Dict[str, Any]]:
        """Invokes local Ollama server if available."""
        url = f"{self.settings.ollama_base_url}/api/chat"
        payload = {
            "model": self.settings.ollama_model,
            "messages": [
                {"role": "system", "content": self._build_system_prompt() + " Respond only with JSON."},
                {"role": "user", "content": self._build_user_prompt(report, lessons)},
            ],
            "format": "json",
            "stream": False,
        }
        try:
            resp = requests.post(url, json=payload, timeout=10)
            if resp.status_code == 200:
                content = resp.json().get("message", {}).get("content", "")
                res = json.loads(content)
                res["model_tag"] = f"Ollama ({self.settings.ollama_model})"
                return self._sanitize_hypothesis(res, report)
        except Exception as e:
            logger.debug(f"Ollama query failed: {e}")
        return None

    def _deterministic_quant_reasoning(
        self,
        report: MarketAnalysisReport,
        lessons: List[str],
    ) -> Dict[str, Any]:
        """
        High-fidelity quantitative reasoning engine.
        Synthesizes technical momentum, support/resistance bounce/breakouts,
        volatility regimes, and applied lessons into a mathematically rigorous hypothesis.
        Guarantees zero hallucinations and deterministic testability.
        """
        s = report.technical_state
        px = report.current_price
        atr = s.atr_14
        pair_cfg = SUPPORTED_PAIRS.get(report.symbol, SUPPORTED_PAIRS["EUR/USD"])

        bullish_score = 0
        bearish_score = 0
        reasons = []

        # 1. EMA Trend alignment
        if s.trend_direction in ["STRONG_BULLISH", "BULLISH"]:
            bullish_score += 2
            reasons.append(f"Price is aligned above key EMAs in {s.trend_direction} formation")
        elif s.trend_direction in ["STRONG_BEARISH", "BEARISH"]:
            bearish_score += 2
            reasons.append(f"Price is trading below key EMAs in {s.trend_direction} formation")

        # 2. RSI Momentum
        if 40.0 <= s.rsi_14 <= 62.0 and s.macd_hist > 0:
            bullish_score += 1.5
            reasons.append(f"RSI ({s.rsi_14:.1f}) exhibits healthy bullish expansion without being overbought")
        elif 38.0 <= s.rsi_14 <= 60.0 and s.macd_hist < 0:
            bearish_score += 1.5
            reasons.append(f"RSI ({s.rsi_14:.1f}) exhibits bearish downward pressure with negative MACD histogram")
        elif s.rsi_14 > 70.0:
            reasons.append(f"RSI ({s.rsi_14:.1f}) indicates overbought extremes; caution on upside")
            bearish_score += 0.5
        elif s.rsi_14 < 30.0:
            reasons.append(f"RSI ({s.rsi_14:.1f}) indicates oversold compression; caution on downside")
            bullish_score += 0.5

        # 3. Bollinger Bands & Volatility Regime
        if report.volatility_regime == "COMPRESSED":
            reasons.append("Bollinger Bandwidth is tightly compressed, anticipating high-volatility momentum release")
        if s.bb_pct_b > 0.8:
            bullish_score += 1.0
            reasons.append("Price is testing upper Bollinger Band with strength")
        elif s.bb_pct_b < 0.2:
            bearish_score += 1.0
            reasons.append("Price is pressing against lower Bollinger Band")

        # 4. Candlestick Patterns
        for pat in report.candle_patterns:
            if "BULLISH" in pat:
                bullish_score += 1.5
                reasons.append(f"Recognized bullish reversal pattern: {pat}")
            elif "BEARISH" in pat:
                bearish_score += 1.5
                reasons.append(f"Recognized bearish reversal pattern: {pat}")

        # 5. Integrate historical memory lessons
        for lesson in lessons:
            if "counter_trend" in lesson.lower() and s.trend_direction != "NEUTRAL":
                # Strengthen adherence to trend
                if "BULLISH" in s.trend_direction:
                    bullish_score += 1.0
                elif "BEARISH" in s.trend_direction:
                    bearish_score += 1.0

        # Synthesize decision
        sl_mult = 1.8
        tp_mult = 2.8  # 1:1.55 Risk-Reward

        if bullish_score > bearish_score and bullish_score >= 3.0:
            direction = "BUY"
            confidence = min(0.85, 0.50 + (bullish_score - bearish_score) * 0.08)
            sl = px - (atr * sl_mult)
            tp = px + (atr * tp_mult)
            invalid = f"Candle close below {sl:.5f} or MACD histogram flipping negative under zero line"
            text = (
                f"Bullish hypothesis based on {'; '.join(reasons[:2])}. "
                f"Targeting upside liquidity towards {tp:.5f} with risk anchored below recent swing support."
            )
        elif bearish_score > bullish_score and bearish_score >= 3.0:
            direction = "SELL"
            confidence = min(0.85, 0.50 + (bearish_score - bullish_score) * 0.08)
            sl = px + (atr * sl_mult)
            tp = px - (atr * tp_mult)
            invalid = f"Candle close above {sl:.5f} or MACD histogram crossing above signal line"
            text = (
                f"Bearish hypothesis based on {'; '.join(reasons[:2])}. "
                f"Targeting downside liquidity towards {tp:.5f} with stop loss above structural resistance."
            )
        else:
            direction = "HOLD"
            confidence = 0.50
            sl = px - (atr * sl_mult)
            tp = px + (atr * tp_mult)
            invalid = "Market remains in consolidation without decisive indicator edge"
            text = (
                f"Neutral stance on {report.symbol}. Mixed signals observed between momentum and price action: "
                f"{'; '.join(reasons[:2]) if reasons else 'waiting for clearer volatility breakout'}."
            )

        return {
            "direction": direction,
            "confidence": round(confidence, 2),
            "hypothesis_text": text,
            "invalidation_criteria": invalid,
            "proposed_entry": round(px, 5),
            "proposed_stop_loss": round(sl, 5),
            "proposed_take_profit": round(tp, 5),
        }

    def _sanitize_hypothesis(self, res: Dict[str, Any], report: MarketAnalysisReport) -> Dict[str, Any]:
        """Ensures LLM response complies with mathematical bounds and pair conventions."""
        px = report.current_price
        atr = report.technical_state.atr_14

        direction = res.get("direction", "HOLD").upper()
        if direction not in ["BUY", "SELL", "HOLD"]:
            direction = "HOLD"

        confidence = float(res.get("confidence", 0.5))
        confidence = max(0.1, min(0.95, confidence))

        entry = float(res.get("proposed_entry", px))
        sl = float(res.get("proposed_stop_loss", px - atr * 1.5))
        tp = float(res.get("proposed_take_profit", px + atr * 2.5))

        # Enforce basic order validity
        if direction == "BUY":
            if sl >= entry:
                sl = entry - (atr * 1.8)
            if tp <= entry:
                tp = entry + (atr * 2.8)
        elif direction == "SELL":
            if sl <= entry:
                sl = entry + (atr * 1.8)
            if tp >= entry:
                tp = entry - (atr * 2.8)

        return {
            "direction": direction,
            "confidence": round(confidence, 2),
            "hypothesis_text": str(res.get("hypothesis_text", "Quantitative momentum evaluation.")),
            "invalidation_criteria": str(res.get("invalidation_criteria", f"Price violation of SL")),
            "proposed_entry": round(entry, 5),
            "proposed_stop_loss": round(sl, 5),
            "proposed_take_profit": round(tp, 5),
            "model_tag": res.get("model_tag", "LLM"),
        }
